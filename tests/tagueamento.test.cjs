const assert=require('node:assert/strict'),t=require('../public/tagueamento/core.js');
let s={workshops:[],subsections:[],equipments:[],instruments:[]};
s=t.addWorkshop(s,{code:'SEEX',name:'Oficina SEEX'},'w');
s=t.addSubsection(s,{workshopId:'w',code:'UN6',name:'Unidade 6'},'sub');
assert.equal(s.subsections[0].tag,'SEEX-UN6');
assert.throws(()=>t.addSubsection(s,{workshopId:'bad',code:'UN7',name:'Outra'},'bad'),/oficina/);
assert.throws(()=>t.addWorkshop(s,{code:'seex',name:'Duplicada'},'dup'),/existe/);
const eq={subsectionId:'sub',type:'R',name:'Reator'};
s=t.addEquipment(s,eq,'eq');s=t.addEquipment(s,eq,'eq2');
assert.equal(s.equipments[0].tag,'SEEX-UN6-R001');assert.equal(s.equipments[1].tag,'SEEX-UN6-R002');
assert.throws(()=>t.addEquipment(s,{...eq,subsectionId:'bad'},'bad'),/subseção/);
const d={equipmentId:'eq',quantity:'P',function:'I',description:'Pressão',loopMode:'new'};
s=t.addInstrument(s,d,'i');assert.equal(s.instruments[0].tag,'SEEX-UN6-R001-PI001');
s=t.addInstrument(s,{...d,function:'T',loopMode:'existing',loop:'001'},'it');assert.equal(s.instruments[1].tag,'SEEX-UN6-R001-PT001');
assert.throws(()=>t.addInstrument(s,{...d,loopMode:'existing',loop:'001'},'dup'),/existe/);
s=t.addInstrument(s,{...d,equipmentId:'eq2',quantity:'T',function:'IA'},'ia');assert.equal(s.instruments.at(-1).tag,'SEEX-UN6-R002-TIA001');
assert.match(t.csv(s),/SEEX-UN6-R001-PI001/);
assert.equal(t.migrate([{parent:'R-1',tag:'PI-123',unit:'U',area:'A'}]).instruments[0].tag,'PI-123');
console.log('Passed: workshops, subsections, parent validation, automatic numbering, full tags, shared loops, duplicates and legacy preservation.');
