const assert=require('node:assert/strict');
const t=require('../public/tagueamento/core.js');
let s={version:2,equipments:[],instruments:[]};
const eq={company:'EMP01',unit:'U01',area:'PROD',type:'R',name:'Reator'};
s=t.addEquipment(s,eq,'eq1');assert.equal(s.equipments[0].tag,'U01-PROD-R-001');
s=t.addEquipment(s,eq,'eq2');assert.equal(s.equipments[1].tag,'U01-PROD-R-002');
const d={equipmentId:'eq1',quantity:'P',function:'I',description:'Manômetro',loopMode:'new'};
s=t.addInstrument(s,d,'i1');assert.equal(s.instruments[0].tag,'PI-001');assert.equal(s.instruments[0].parent,'U01-PROD-R-001');
s=t.addInstrument(s,{...d,quantity:'T'},'i2');assert.equal(s.instruments[1].tag,'TI-002');
s=t.addInstrument(s,{...d,function:'T',loopMode:'existing',loop:'001'},'i3');assert.equal(s.instruments[2].tag,'PT-001');
assert.throws(()=>t.addInstrument(s,{...d,loopMode:'existing',loop:'001'},'dupe'),/já existe/);
assert.throws(()=>t.addInstrument(s,{...d,equipmentId:'invalid'},'bad'),/primeiro/);
assert.throws(()=>t.addInstrument(s,{...d,quantity:'T',loopMode:'existing',loop:'001'},'bad'),/mesma grandeza/);
assert.throws(()=>t.addEquipment(s,{...eq,existing:'PI-001'},'bad'),/já existe/);
s=t.addEquipment(s,{...eq,company:'EMP02'},'other');
s=t.addInstrument(s,{...d,equipmentId:'other'},'other-i');assert.equal(s.instruments.at(-1).tag,'PI-001');
assert.match(t.csv(s),/equipamento_id/);assert.match(t.csv({...s,equipments:[{...s.equipments[0],name:'=1+1'}]}),/'=1\+1/);
const legacy=t.migrate([{id:'old',tag:'PI-123',parent:'R-1',unit:'U1',area:'A1',equipment:'Reator',description:'Pressão',quantity:'P',function:'I',loop:'123'}]);assert.equal(legacy.instruments[0].tag,'PI-123');assert.equal(legacy.instruments[0].equipmentId,legacy.equipments[0].id);
console.log('Passed: hierarchy, sequence, parent links, shared loops, collision scope, migration and CSV safety.');
